In this question you are to define a version of the standard QuickCheck function listOf in two ways. In both definitions you may not use vectorOf, and you may not use any functions not explicitly listed in the given list of functions except for arbitrary :: Gen Int. 

1. with the help of recursion
2. without recursion, using the given standard functions (except for vectorOf)
-}

listOf1, listOf2 :: Gen a -> Gen [a]
listOf1 g = do
     len <- arbitrary :: Gen Int
     go (abs len)

    where go 0 = return []
          go n = do 
                a <- g
                as <- go (n-1)
                return (a:as)

listOf2 g = do
     len <- arbitrary
     sequence $ replicate (abs len) g

{- Define a function listContaining :: Gen a -> a -> Gen [a]  such that g `ListContaining` x generates lists of elements of the same type as x, such that (i) the list is guaranteed to contain at least one copy of x, and (ii) all other elements are generated by g (which may or may not generate other copies of x). -}

listContaining :: Gen a -> a -> Gen [a]
listContaining g a = do 
    front <- listOf g
    back <- listOf g
    return (front ++ [a] ++ back)

