{-
This example workplace represents a building with 6 floors, numbered 0 to 5. The number of steps between floor 0 (ground floor) and floor 1 is 30, whereas the number between floor 1 and 2 is 20, etc.

The activity of an employee can be modelled as a list of the floors they visit in a working day.

-}

type Activity = [Floor]

-- For example, [2,1,5,0] represents the movements of Dave, who wakes up in his office on floor 2, visits the canteen on floor 1, the coffee room on floor 5, then leaves on floor 0. 

-- Define a function 

stepCount :: Workplace -> Activity -> Steps

-- which computes the total number of steps in a given day's activity. 
stepCount stairs acts = 
    let moves = zip acts (drop 1 acts)
        moveLength (start,end) = sum . take upper . drop lower $ stairs
                                 where [lower,upper] = sort [start,end]
    in sum $ map moveLength moves        

{-
The workplace want to install a lift (elevator).  Unfortunately they can only afford a lift that goes between two consecutive floors.  To decide which floor the lift should be installed on (we say that the lift is on floor n if it goes between floors n and n+1) they take the data from the last year (a list of the activities of all employees), and choose to install the lift on the floor that will minimise the number of steps that are taken - assuming that everyone will always take the lift when possible!

Define a function
-}

bestPlace :: Workplace -> [Activity] -> Floor

-- which calculates the best place for the list.  If there are several best choices then you may return any one of them. 

-- total steps for a given collection of activities
totalSteps :: Workplace -> [Activity] -> Steps
totalSteps stairs = sum . map (stepCount stairs)

-- effect of installing a lift at a given floor (assumes that the floor is valid) is to set the number of steps to zero.
installLift :: Floor -> Workplace -> Workplace
installLift floor stairs = below ++ [0] ++ above
       where (below,_:above) = splitAt floor stairs 

bestPlace stairs activity = snd $ minimum allOutcomes
  where
    choices             = [0..length stairs - 1] -- possible floors
    installEffect       :: Floor -> Steps
    installEffect floor = totalSteps (installLift floor stairs) activity 
    allOutcomes         :: [(Steps,Floor)]
    allOutcomes         = [(installEffect floor, floor) | floor <- choices]

