-- Consider a "rose tree" - a tree with nodes of type a having zero or more subtrees: 
data Rose a = Node a [Rose a]
  deriving (Eq,Show)

-- Define a zip function
zipRose :: Rose a -> Rose b -> Rose (a,b)

-- So that, for example, zipping the trees A and B gives the Tree C pictured below:

zipRose (Node a tas) (Node b tbs) = Node (a,b) $ zipWith zipRose tas tbs


-- Let us say that a rose tree is "list-shaped" if every node matches either the pattern
-- Node x [t] or Node x [].

-- Define a function 

fromList :: [a] -> Rose a

-- which converts any non-empty list into the corresponding list-shaped tree.   It should be undefined on the empty list. 

fromList [x]    = Node x []
fromList (x:xs) = Node x [fromList xs]

-- using fromList, define prop_zipRose, a property that checks that zipRose does essentially the same thing as zip when its inputs are list-shaped. 

prop_zipRose :: Int -> [Int] -> Bool -> [Bool] -> Bool
prop_zipRose a as b bs = 
   zipRose (fromList as') (fromList bs') == fromList (zip as' bs')
      where as' = a:as
            bs' = b:bs  
       
